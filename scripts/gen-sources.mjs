// Runs before dev/build/typecheck and writes two files from src/motion/items/:
// - sources.generated.ts: each component's source files for the Code tab (every .tsx/.ts/.css except index.ts).
// - meta.generated.ts: plain metadata (slug, name, …) for server code such as routes and the sitemap, which must
//   not import the components themselves, since those use client-only React hooks.
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join } from "node:path";

const root = join(process.cwd(), "src/motion/items");
const sources = {};
const meta = [];
const field = (src, key, slug) => {
  const m = src.match(new RegExp(`^\\s*${key}:\\s*"((?:[^"\\\\]|\\\\.)*)"`, "m"));
  if (!m) throw new Error(`gen-sources: ${slug}/index.ts needs a string literal for "${key}"`);
  return JSON.parse(`"${m[1]}"`);
};

for (const slug of readdirSync(root).sort()) {
  const dir = join(root, slug);
  if (!statSync(dir).isDirectory()) continue;
  sources[slug] = readdirSync(dir)
    .filter((f) => /\.(tsx?|css)$/.test(f) && f !== "index.ts")
    .sort()
    .map((f) => ({ file: f, code: readFileSync(join(dir, f), "utf8") }));
  const index = readFileSync(join(dir, "index.ts"), "utf8");
  const entry = Object.fromEntries(["slug", "name", "description", "category", "addedAt"].map((k) => [k, field(index, k, slug)]));
  if (entry.slug !== slug) throw new Error(`gen-sources: folder ${slug} declares slug "${entry.slug}"`);
  meta.push(entry);
}

const header = "// Generated by scripts/gen-sources.mjs. Do not edit.\n";
writeFileSync(
  join(process.cwd(), "src/motion/sources.generated.ts"),
  header + "export const SOURCES: Record<string, { file: string; code: string }[]> = " + JSON.stringify(sources, null, 1) + ";\n",
);
writeFileSync(
  join(process.cwd(), "src/motion/meta.generated.ts"),
  header +
    "export type MotionMeta = { slug: string; name: string; description: string; category: string; addedAt: string };\n" +
    "export const MOTION_META: MotionMeta[] = " + JSON.stringify(meta, null, 1) + ";\n",
);
console.log(`gen-sources: ${meta.length} components`);
