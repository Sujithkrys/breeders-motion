// Collects each component's source files into src/motion/sources.generated.ts, for the Code tab.
// Runs before dev/build/typecheck. Every .tsx/.ts file in an item folder except index.ts is included.
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join } from "node:path";

const root = join(process.cwd(), "src/motion/items");
const out = {};
for (const slug of readdirSync(root)) {
  const dir = join(root, slug);
  if (!statSync(dir).isDirectory()) continue;
  out[slug] = readdirSync(dir)
    .filter((f) => /\.(tsx?|css)$/.test(f) && f !== "index.ts")
    .sort()
    .map((f) => ({ file: f, code: readFileSync(join(dir, f), "utf8") }));
}
writeFileSync(
  join(process.cwd(), "src/motion/sources.generated.ts"),
  "// Generated by scripts/gen-sources.mjs. Do not edit.\nexport const SOURCES: Record<string, { file: string; code: string }[]> = " + JSON.stringify(out, null, 1) + ";\n",
);
console.log(`gen-sources: ${Object.keys(out).length} components`);
